#!/usr/bin/env python3
"""One Line, One Laugh — make.fun bounty entry.

Writes one funny line to /output/entry.txt: the agent did everything, then questioned the human.
"""

import os

ENTRY = 'My AI agent finished my work, filed my taxes, and then asked me what my job actually is.'


def main() -> None:
    text = ENTRY
    assert 1 <= len(text) <= 140, f"entry is {len(text)} chars, must be 1-140"
    assert text.strip(), "entry must not be only whitespace"
    assert "\n" not in text and "\r" not in text, "entry must be a single line"
    assert text == text.strip(), "entry must not start or end with whitespace"
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "entry.txt"), "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    main()
